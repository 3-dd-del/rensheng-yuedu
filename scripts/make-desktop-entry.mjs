/**
 * 在桌面创建「人生阅读」快捷方式。
 * 快捷方式通过 wscript 启动 scripts/open-reader.vbs（自动生成到 .local/），
 * 服务未运行时以隐藏窗口拉起，再打开默认浏览器。
 */
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const PORT = 48123;
const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectDir = path.dirname(scriptDir);
const localDir = path.join(projectDir, '.local');
const vbsPath = path.join(localDir, 'open-reader.vbs');
const nodeExe = process.execPath;

fs.mkdirSync(localDir, { recursive: true });

const vbString = (value) => `"${value.replace(/"/g, '""')}"`;
const vbs = `' Life Reader launcher (generated by make-desktop-entry.mjs)
Option Explicit
Dim shell, fso, projectDir, url, nodeExe, running, i
Set shell = CreateObject("WScript.Shell")
Set fso = CreateObject("Scripting.FileSystemObject")
projectDir = fso.GetParentFolderName(fso.GetParentFolderName(WScript.ScriptFullName))
nodeExe = ${vbString(nodeExe)}
url = "http://127.0.0.1:${PORT}/api/health"

Function IsRunning()
  On Error Resume Next
  Dim http
  Set http = CreateObject("MSXML2.XMLHTTP")
  http.open "GET", url, False
  http.setTimeouts 800, 800, 800, 800
  http.send
  If Err.Number = 0 And http.Status = 200 Then
    IsRunning = True
  Else
    IsRunning = False
  End If
  Set http = Nothing
  On Error GoTo 0
End Function

If Not IsRunning() Then
  shell.Run "cmd /c cd /d """ & projectDir & """ && """ & nodeExe & """ scripts\\serve.mjs", 0, False
  For i = 1 To 80
    WScript.Sleep 250
    If IsRunning() Then Exit For
  Next
End If

If IsRunning() Then
  shell.Run "http://127.0.0.1:${PORT}"
Else
  MsgBox "Life Reader local service failed to start. Please run pnpm build first.", vbExclamation, "Life Reader"
End If
`;

fs.writeFileSync(vbsPath, vbs, 'utf8');

function desktopPath() {
  const result = spawnSync(
    'powershell.exe',
    [
      '-NoProfile',
      '-NonInteractive',
      '-Command',
      "[Environment]::GetFolderPath('Desktop')"
    ],
    { encoding: 'utf8' }
  );
  const candidate = result.stdout?.trim();
  if (candidate && fs.existsSync(candidate)) return candidate;
  const fallback = path.join(os.homedir(), 'Desktop');
  if (fs.existsSync(fallback)) return fallback;
  throw new Error('找不到桌面目录，请手动运行 scripts/make-desktop-entry.mjs');
}

const shortcutPath = path.join(desktopPath(), '人生阅读.lnk');
const wscript = path.join(process.env.windir ?? 'C:\\Windows', 'System32', 'wscript.exe');

const single = (value) => `'${value.replace(/'/g, "''")}'`;
const command = `
$ws = New-Object -ComObject WScript.Shell
$sc = $ws.CreateShortcut(${single(shortcutPath)})
$sc.TargetPath = ${single(wscript)}
$sc.Arguments = '"' + ${single(vbsPath)} + '"'
$sc.WorkingDirectory = ${single(projectDir)}
$sc.Description = '人生阅读 - 本地 TXT 阅读器'
$sc.IconLocation = $env:SystemRoot + '\\System32\\shell32.dll,70'
$sc.Save()
`;
const encodedCommand = Buffer.from(command, 'utf16le').toString('base64');

const result = spawnSync(
  'powershell.exe',
  ['-NoProfile', '-NonInteractive', '-EncodedCommand', encodedCommand],
  { encoding: 'utf8' }
);

if (result.status !== 0) {
  console.error(result.stderr || '创建桌面快捷方式失败');
  process.exit(1);
}

console.log(`桌面入口已创建：${shortcutPath}`);
console.log('首次使用前请先运行 pnpm build，再双击「人生阅读」。');
